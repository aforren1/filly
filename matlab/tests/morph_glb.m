function bytes = morph_glb()
% MORPH_GLB  GLB bytes of one triangle facing +Z with one morph target that moves it by +1 in Z.
positions = single([0 0 0; 1 0 0; 0 1 0])';
target = single([0 0 1; 0 0 1; 0 0 1])';
indices = uint16([0 1 2 0]);  % the fourth value pads the buffer to 4 bytes
binary = [typecast(positions(:)', 'uint8'), typecast(target(:)', 'uint8'), typecast(indices, 'uint8')];
document = ['{"asset":{"version":"2.0"},"scene":0,"scenes":[{"nodes":[0]}],' ...
    '"nodes":[{"mesh":0,"name":"morph"}],' ...
    '"meshes":[{"primitives":[{"attributes":{"POSITION":0},"indices":2,"targets":[{"POSITION":1}]}],"weights":[0]}],' ...
    '"accessors":[{"bufferView":0,"componentType":5126,"count":3,"type":"VEC3","min":[0,0,0],"max":[1,1,0]},' ...
    '{"bufferView":1,"componentType":5126,"count":3,"type":"VEC3","min":[0,0,1],"max":[0,0,1]},' ...
    '{"bufferView":2,"componentType":5123,"count":3,"type":"SCALAR"}],' ...
    '"bufferViews":[{"buffer":0,"byteOffset":0,"byteLength":36},{"buffer":0,"byteOffset":36,"byteLength":36},' ...
    '{"buffer":0,"byteOffset":72,"byteLength":6}],"buffers":[{"byteLength":80}]}'];
json = uint8(document);
json = [json, repmat(uint8(' '), 1, mod(-numel(json), 4))];
total = 12 + 8 + numel(json) + 8 + numel(binary);
bytes = [uint8('glTF'), typecast(uint32([2 total]), 'uint8'), ...
    typecast(uint32(numel(json)), 'uint8'), uint8('JSON'), json, ...
    typecast(uint32(numel(binary)), 'uint8'), uint8('BIN'), uint8(0), binary];
end
